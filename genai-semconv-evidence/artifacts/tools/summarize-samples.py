import json, glob, os, sys
S = os.path.expanduser("~/work/evidence/sample-payloads")
def val(v):
    for k, x in v.items():
        if k == "arrayValue": return [val(i) for i in x.get("values", [])]
        return x
out = []
cases = sorted(d for d in os.listdir(S) if os.path.isdir(os.path.join(S, d)))
for c in cases:
    out.append(f"## {c}\n")
    for f in sorted(glob.glob(os.path.join(S, c, "http", "*traces.json"))):
        b = json.load(open(f))
        for rs in b["resourceSpans"]:
            rkeys = sorted(a["key"] for a in rs["resource"]["attributes"])
            for ss in rs["scopeSpans"]:
                for sp in ss["spans"]:
                    attrs = {a["key"]: val(a["value"]) for a in sp["attributes"]}
                    sel = {k: attrs[k] for k in sorted(attrs) if k.startswith(("gen_ai.", "error.")) }
                    out.append(f"- span `{sp['name']}` kind={sp.get('kind')} status={sp.get('status',{})} scope.schemaUrl={ss.get('schemaUrl')} resource.schemaUrl={rs.get('schemaUrl')}")
                    out.append(f"  - gen_ai/error attrs: {json.dumps(sel)}")
                    out.append(f"  - resource keys (non gh-aw/github): {[k for k in rkeys if not k.startswith(('gh-aw.','github.'))]}")
    for f in sorted(glob.glob(os.path.join(S, c, "http", "*metrics.json"))):
        b = json.load(open(f))
        names = []
        for rm in b["resourceMetrics"]:
            for sm in rm["scopeMetrics"]:
                for m in sm["metrics"]:
                    kind = next(k for k in ("sum","gauge","histogram") if k in m)
                    dps = m[kind]["dataPoints"]
                    keys = sorted({a["key"] for d in dps for a in d.get("attributes", [])})
                    names.append(f"  - `{m['name']}` {kind} dp={len(dps)} attrs={keys}")
        out.append("- metrics:"); out += names
    out.append("")
open(os.path.join(S, "SUMMARY.md"), "w").write("# Sample payload summary (generated by tools/summarize-samples.py)\n\n" + "\n".join(out) + "\n")
print("\n".join(out))